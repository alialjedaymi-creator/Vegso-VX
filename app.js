// 5. Invoices and Accounting Renderer
function renderInvoicesTable() {
    const search = document.getElementById("invoice-search-input").value.toLowerCase().trim();
    const statusFilter = document.getElementById("invoice-status-filter").value;

    const tbody = document.getElementById("invoices-table-tbody");
    tbody.innerHTML = "";

    const filtered = db.invoices.filter(inv => {
        const patient = db.patients.find(p => p.id === inv.patientId);
        const patientName = patient ? patient.name.toLowerCase() : "";
        const matchesSearch = inv.id.toString().includes(search) || patientName.includes(search);
        const matchesStatus = statusFilter === "" || inv.status === statusFilter;
        return matchesSearch && matchesStatus;
    });

    // Calculate Summary Stats
    let paidSum = 0;
    let pendingSum = 0;
    let unpaidSum = 0;

    db.invoices.forEach(inv => {
        if (inv.status === "paid") paidSum += inv.total;
        else if (inv.status === "pending") pendingSum += inv.total;
        else if (inv.status === "unpaid") unpaidSum += inv.total;
    });

    const currency = translations[currentLang]["currency"];
    document.getElementById("fin-paid-total").textContent = `${paidSum} ${currency}`;
    document.getElementById("fin-pending-total").textContent = `${pendingSum} ${currency}`;
    document.getElementById("fin-unpaid-total").textContent = `${unpaidSum} ${currency}`;

    if (filtered.length === 0) {
        tbody.innerHTML = `<tr><td colspan="6" style="text-align: center; color: var(--text-muted)">${currentLang === "ar" ? "لا توجد فواتير تطابق البحث" : "No invoices found matching criteria"}</td></tr>`;
        return;
    }

    filtered.forEach(inv => {
        const patient = db.patients.find(p => p.id === inv.patientId);
        const tr = document.createElement("tr");
        
        tr.innerHTML = `
            <td><strong>#${inv.id}</strong></td>
            <td><strong>${patient ? patient.name : "Unknown"}</strong></td>
            <td>${inv.date}</td>
            <td>${inv.total} ${currency}</td>
            <td><span class="status-pill status-${inv.status}">${translations[currentLang][`invoice-status-${inv.status}`]}</span></td>
            <td>
                <div class="form-group-row">
                    <button class="btn btn-sm btn-outline view-invoice-btn" data-id="${inv.id}">
                        <i class="fa-solid fa-print"></i> ${translations[currentLang]["actions-view-invoice"]}
                    </button>
                    <button class="btn btn-sm btn-outline btn-icon delete-invoice-btn" data-id="${inv.id}" style="color: var(--color-rose)">
                        <i class="fa-solid fa-trash"></i>
                    </button>
                </div>
            </td>
        `;
        tbody.appendChild(tr);
    });

    // View Invoice print window click handler
    tbody.querySelectorAll(".view-invoice-btn").forEach(btn => {
        btn.addEventListener("click", () => {
            const invId = parseInt(btn.getAttribute("data-id"));
            const invoice = db.invoices.find(i => i.id === invId);
            if (invoice) {
                showPrintInvoiceModal(invoice);
            }
        });
    });

    // Delete Invoice handler
    tbody.querySelectorAll(".delete-invoice-btn").forEach(btn => {
        btn.addEventListener("click", () => {
            const invId = parseInt(btn.getAttribute("data-id"));
            if (confirm(currentLang === "ar" ? "هل أنت متأكد من حذف هذه الفاتورة المالية نهائياً؟" : "Are you sure you want to permanently delete this financial invoice?")) {
                db.invoices = db.invoices.filter(i => i.id !== invId);
                saveDatabase();
                renderAll();
            }
        });
    });
}

