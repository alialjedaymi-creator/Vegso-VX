function collectSystemIssues() {
    const issues = [];

    db.appointments.forEach(app => {
        if (!app.patientId || !db.patients.some(p => p.id === app.patientId)) {
            issues.push({
                icon: 'fa-user-slash',
                title: currentLang === 'ar' ? 'طلب غير صالح بدون عميل' : 'Invalid booking without patient',
                detail: currentLang === 'ar' ? `الطلبية ${app.id} لا تحتوي على عميل مسجل أو معرف العميل غير موجود.` : `Appointment ${app.id} has no valid patient or missing patient reference.`,
                level: 'error'
            });
        }
        if (!app.doctorId || !db.doctors.some(d => d.id === app.doctorId)) {
            issues.push({
                icon: 'fa-user-doctor',
                title: currentLang === 'ar' ? 'طلب غير صالح بدون صنف دوائي' : 'Invalid booking without doctor',
                detail: currentLang === 'ar' ? `الطلبية ${app.id} غير مرتبطة بصنف دوائي صالح.` : `Appointment ${app.id} has no valid doctor assignment.`,
                level: 'error'
            });
        }
    });

    db.patients.forEach(patient => {
        if (!patient.name || !patient.phone) {
            issues.push({
                icon: 'fa-user-exclamation',
                title: currentLang === 'ar' ? 'عميل ناقص البيانات' : 'Incomplete patient record',
                detail: currentLang === 'ar' ? `العميل ${patient.id} يفتقد اسماً أو رقم هاتف.` : `Patient ${patient.id} is missing name or phone number.`,
                level: 'warning'
            });
        }
    });

    db.doctors.forEach(doc => {
        if (!doc.name || !doc.specialty) {
            issues.push({
                icon: 'fa-stethoscope',
                title: currentLang === 'ar' ? 'صنف دوائي ناقص البيانات' : 'Incomplete doctor profile',
                detail: currentLang === 'ar' ? `الصنف الدوائي ${doc.id} يحتاج إلى ضبط الاسم أو التصنيف.` : `Doctor ${doc.id} needs name or specialty defined.`,
                level: 'warning'
            });
        }
    });

    db.invoices.forEach(inv => {
        if (!inv.patientId || !db.patients.some(p => p.id === inv.patientId)) {
            issues.push({
                icon: 'fa-file-invoice',
                title: currentLang === 'ar' ? 'فاتورة غير مرتبطة بعميل' : 'Invoice with missing patient',
                detail: currentLang === 'ar' ? `الفاتورة ${inv.id} ترتبط بعميل غير موجود.` : `Invoice ${inv.id} points to a missing patient.`,
                level: 'warning'
            });
        }
    });

    return issues;
}

function renderNotificationsPanel() {
    const badge = document.getElementById('noti-count');
    const list = document.getElementById('noti-list');
    if (!badge || !list) return;

    let bookings = [];
    let invoices = [];
    let issues = [];

    if (currentRole === 'employee') {
        bookings = db.appointments.filter(a => a.status === 'pending')
            .sort((a, b) => (a.date + a.time).localeCompare(b.date + b.time));
    } else if (currentRole === 'supervisor') {
        bookings = db.appointments.filter(a => a.status === 'pending')
            .sort((a, b) => (a.date + a.time).localeCompare(b.date + b.time));
        invoices = db.invoices.filter(i => i.status === 'unpaid' || i.status === 'pending');
    } else {
        bookings = db.appointments.filter(a => a.status === 'pending')
            .sort((a, b) => (a.date + a.time).localeCompare(b.date + b.time));
        invoices = db.invoices.filter(i => i.status === 'unpaid' || i.status === 'pending');
        issues = collectSystemIssues();
    }

    const count = bookings.length + invoices.length + issues.length;
    badge.textContent = count;
    
    if (count > 0) {
        badge.style.display = 'flex';
        badge.classList.add('pulse-badge');
    } else {
        badge.style.display = 'none';
        badge.classList.remove('pulse-badge');
    }

    list.innerHTML = '';

    if (count === 0) {
        list.innerHTML = `
            <div class="noti-empty">
                <i class="fa-solid fa-bell-slash"></i>
                <p>${currentLang === 'ar' ? 'لا توجد تنبيهات عاجلة حالياً' : 'No urgent alerts at the moment'}</p>
            </div>`;
        return;
    }

    const renderSection = (title, items, renderItem, emptyText) => {
        const section = document.createElement('div');
        section.className = 'noti-section';
        section.innerHTML = `
            <div class="noti-section-header">
                <span class="noti-section-title">${title}</span>
                <span class="noti-badge">${items.length}</span>
            </div>
            <div class="noti-section-list"></div>`;
        const container = section.querySelector('.noti-section-list');

        if (!items.length) {
            container.innerHTML = `<div class="noti-empty"><p>${emptyText}</p></div>`;
        } else {
            items.forEach(item => container.appendChild(renderItem(item)));
        }
        return section;
    };

    const createBookingItem = app => {
        const patient = db.patients.find(p => p.id === app.patientId);
        const doctor = db.doctors.find(d => d.id === app.doctorId);
        const statusLabel = translations[currentLang][`status-${app.status}`] || app.status;
        const item = document.createElement('div');
        item.className = 'noti-item';
        item.dataset.notiType = 'appointment';
        item.dataset.notiId = app.id;
        item.innerHTML = `
            <div class="noti-item-icon status-${app.status}">
                <i class="fa-solid ${app.status === 'pending' ? 'fa-clock' : 'fa-calendar-check'}"></i>
            </div>
            <div class="noti-item-body">
                <strong>${patient ? patient.name : (currentLang === 'ar' ? 'عميل غير معروف' : 'Unknown patient')}</strong>
                <p>${currentLang === 'ar' ? 'الصنف الدوائي' : 'Doctor'}: ${doctor ? (currentLang === 'ar' ? doctor.name : doctor.nameEn) : (currentLang === 'ar' ? 'غير معروف' : 'Unknown')}</p>
                <p>${app.date} • ${app.time}</p>
            </div>
            <span class="noti-badge">${statusLabel}</span>`;
        item.addEventListener('click', () => handleNotificationItemClick({ type: 'appointment', id: app.id }));
        return item;
    };

    const createInvoiceItem = inv => {
        const patient = db.patients.find(p => p.id === inv.patientId);
        const currencyText = translations[currentLang]["currency"];
        const item = document.createElement('div');
        item.className = 'noti-item';
        item.dataset.notiType = 'invoice';
        item.dataset.notiId = inv.id;
        item.innerHTML = `
            <div class="noti-item-icon noti-warning" style="background: rgba(234, 179, 8, 0.15); color: #eab308; display: flex; align-items: center; justify-content: center; width: 36px; height: 36px; border-radius: 50%;">
                <i class="fa-solid fa-file-invoice-dollar"></i>
            </div>
            <div class="noti-item-body">
                <strong>${currentLang === 'ar' ? 'فاتورة غير مدفوعة' : 'Unpaid invoice'}</strong>
                <p>${currentLang === 'ar' ? 'العميل / الصيدلية' : 'Patient'}: ${patient ? patient.name : (currentLang === 'ar' ? 'غير معروف' : 'Unknown')}</p>
                <p>${currentLang === 'ar' ? 'المبلغ' : 'Amount'}: ${inv.total || inv.amount || '—'} ${currencyText}</p>
            </div>
            <span class="noti-badge">${currentLang === 'ar' ? 'غير مدفوعة' : 'Unpaid'}</span>`;
        item.addEventListener('click', () => handleNotificationItemClick({ type: 'invoice', id: inv.id }));
        return item;
    };

    const createIssueItem = iss => {
        const item = document.createElement('div');
        item.className = 'noti-item';
        const color = iss.level === 'error' ? '#f43f5e' : '#eab308';
        const bg = iss.level === 'error' ? 'rgba(244, 63, 94, 0.15)' : 'rgba(234, 179, 8, 0.15)';
        item.innerHTML = `
            <div class="noti-item-icon" style="background: ${bg}; color: ${color}; display: flex; align-items: center; justify-content: center; width: 36px; height: 36px; border-radius: 50%;">
                <i class="fa-solid ${iss.icon}"></i>
            </div>
            <div class="noti-item-body">
                <strong>${iss.title}</strong>
                <p>${iss.detail}</p>
            </div>
            <span class="noti-badge" style="background: ${bg}; color: ${color};">${iss.level === 'error' ? (currentLang === 'ar' ? 'خطأ' : 'Error') : (currentLang === 'ar' ? 'تحذير' : 'Warning')}</span>`;
        return item;
    };

    if (bookings.length > 0) {
        list.appendChild(renderSection(
            currentLang === 'ar' ? 'طلبيات قيد التحضير والتجهيز' : 'Bookings & Appointments',
            bookings,
            createBookingItem,
            currentLang === 'ar' ? 'لا توجد طلبيات قيد الانتظار' : 'No pending bookings'
        ));
    }

    if (invoices.length > 0) {
        list.appendChild(renderSection(
            currentLang === 'ar' ? 'الفواتير غير المدفوعة' : 'Unpaid Invoices',
            invoices,
            createInvoiceItem,
            currentLang === 'ar' ? 'لا توجد فواتير غير مدفوعة' : 'No unpaid invoices'
        ));
    }

    if (issues.length > 0) {
        list.appendChild(renderSection(
            currentLang === 'ar' ? 'مشاكل النظام المكتشفة' : 'Detected System Issues',
            issues,
            createIssueItem,
            currentLang === 'ar' ? 'لا توجد مشاكل تم الكشف عنها' : 'No issues detected'
        ));
    }
}

function toggleNotificationPanel() {
    const panel = document.getElementById('noti-panel');
    const wrapper = document.getElementById('notifications-wrapper');
    const isOpen = panel.classList.contains('open');
    if (isOpen) {
        panel.classList.remove('open');
        panel.style.left = '';
        panel.style.right = '';
        panel.style.top = '';
    } else {
        renderNotificationsPanel();
        panel.classList.add('open');

        if (wrapper) {
            const rect = wrapper.getBoundingClientRect();
            panel.style.top = `${Math.min(rect.bottom + 10, window.innerHeight - panel.offsetHeight - 16)}px`;
            panel.style.left = '';
            panel.style.right = '16px';
        }
    }
}

function handleNotificationItemClick({ type, id }) {
    if (type === 'appointment') {
        navigateToAppointmentDetail(id);
    } else if (type === 'invoice') {
        navigateToInvoiceDetail(id);
    }
    document.getElementById('noti-panel').classList.remove('open');
}

function navigateToAppointmentDetail(appId) {
    const appointment = db.appointments.find(a => a.id === appId);
    if (!appointment) return;

    selectedAppointmentId = appId;
    switchPanel('appointments');
    updateSidebarActive('appointments');

    document.getElementById('appointment-doctor-filter').value = appointment.doctorId;
    document.getElementById('appointment-status-filter').value = '';
    document.getElementById('appointment-date-filter').value = appointment.date;

    renderAppointmentsTable();
}

function navigateToInvoiceDetail(invId) {
    const invoice = db.invoices.find(i => i.id === invId);
    if (!invoice) return;

    switchPanel('billing');
    updateSidebarActive('billing');
    renderInvoicesTable();
    showPrintInvoiceModal(invoice);
}

function updateSidebarActive(panelId) {
    document.querySelectorAll('.sidebar-menu li').forEach(li => {
        li.classList.toggle('active', li.getAttribute('data-panel') === panelId);
    });
}

function navigateToPanel(panelId) {
    switchPanel(panelId);
    updateSidebarActive(panelId);
}

