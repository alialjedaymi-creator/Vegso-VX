// Generate sequential IDs
function generateNewId(list, base) {
    if (list.length === 0) return base + 1;
    const ids = list.map(item => item.id);
    return Math.max(...ids) + 1;
}

// Switch between SPA views with smooth transition
function switchPanel(panelId) {
    const panels = document.querySelectorAll(".content-panel");
    panels.forEach(panel => {
        panel.classList.remove("active");
        if (panel.id === `${panelId}-panel`) {
            panel.classList.add("active");
        }
    });
    // Trigger animations or specific charts redraw if dashboard is active
    if (panelId === "dashboard") {
        renderDashboardStats();
    } else if (panelId === "settings") {
        populateSettingsFields();
        renderSettingsDoctorsTable();
    }
}

// Modal handling logic
