// Load DB from LocalStorage or seed defaults
function loadDatabase() {
    const savedDb = localStorage.getItem("clinic_management_db");
    if (savedDb) {
        db = JSON.parse(savedDb);
        if (!db.config) {
            db.config = { ...INITIAL_DATABASE.config };
            saveDatabase();
        }
    } else {
        db = INITIAL_DATABASE;
        saveDatabase();
    }
}

