// Toast Notifications Helper Function
function showToast(message, type = 'success') {
    let container = document.getElementById('toast-container');
    if (!container) {
        container = document.createElement('div');
        container.id = 'toast-container';
        document.body.appendChild(container);
    }
    
    const toast = document.createElement('div');
    toast.className = `toast toast-${type}`;
    
    let icon = 'fa-circle-check';
    let color = '#10b981'; // emerald
    if (type === 'error') {
        icon = 'fa-circle-xmark';
        color = '#f43f5e'; // rose
    } else if (type === 'warning') {
        icon = 'fa-triangle-exclamation';
        color = '#eab308'; // gold
    } else if (type === 'info') {
        icon = 'fa-circle-info';
        color = '#3b82f6'; // blue
    }
    
    toast.innerHTML = `
        <i class="fa-solid ${icon}" style="color: ${color}; font-size: 20px;"></i>
        <div style="flex-grow: 1;">
            <p style="margin: 0; font-size: 13px; font-weight: 600;">${message}</p>
        </div>
        <button style="background: none; border: none; color: var(--text-muted, #888); cursor: pointer; padding: 0; font-size: 16px; line-height: 1;" onclick="this.parentElement.remove()">&times;</button>
    `;
    
    container.appendChild(toast);
    
    // Trigger transition
    setTimeout(() => {
        toast.classList.add('show');
    }, 10);
    
    // Auto-remove
    setTimeout(() => {
        toast.classList.remove('show');
        toast.classList.add('hide');
        setTimeout(() => {
            toast.remove();
        }, 400);
    }, 4000);
}

