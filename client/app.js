// 1. Dashboard Renderer
function renderDashboardStats() {
    document.getElementById("dash-total-patients").textContent = db.patients.length;
    
    // Today's appointments count
    const todayStr = new Date().toISOString().split("T")[0];
    const todayApps = db.appointments.filter(a => a.date === todayStr);
    document.getElementById("dash-today-appointments").textContent = todayApps.length;

    // Today's revenue calculation
    const todayInvoices = db.invoices.filter(i => i.date === todayStr && i.status === "paid");
    const todayRevSum = todayInvoices.reduce((sum, inv) => sum + inv.total, 0);
    const currency = translations[currentLang]["currency"];
    document.getElementById("dash-today-revenue").textContent = `${todayRevSum} ${currency}`;

    // Active doctors count
    const activeDocsCount = db.doctors.filter(d => d.status === "available").length;
    document.getElementById("dash-active-doctors").textContent = `${activeDocsCount} / ${db.doctors.length}`;

    // Render Recent appointments table
    const sortedApps = [...db.appointments]
        .filter(a => a.status === "pending" || a.status === "confirmed")
        .sort((a, b) => a.time.localeCompare(b.time));
        
    const tbody = document.getElementById("dash-recent-appointments-tbody");
    tbody.innerHTML = "";

    if (sortedApps.length === 0) {
        tbody.innerHTML = `<tr><td colspan="4" style="text-align: center; color: var(--text-muted)">${currentLang === "ar" ? "لا توجد مواعيد معلقة اليوم" : "No pending appointments today"}</td></tr>`;
    } else {
        sortedApps.slice(0, 5).forEach(app => {
            const patient = db.patients.find(p => p.id === app.patientId);
            const doctor = db.doctors.find(d => d.id === app.doctorId);
            const tr = document.createElement("tr");
            tr.innerHTML = `
                <td><strong>${patient ? patient.name : "Unknown"}</strong></td>
                <td>${doctor ? (currentLang === "ar" ? doctor.name : doctor.nameEn) : "Unknown"}</td>
                <td><i class="fa-regular fa-clock" style="color: var(--accent-secondary)"></i> ${app.time}</td>
                <td><span class="status-pill status-${app.status}">${translations[currentLang][`status-${app.status}`]}</span></td>
            `;
            tbody.appendChild(tr);
        });
    }

    renderDashboardCharts();
    renderDashboardShortcuts();
}

// Dashboard Interactive Charts Rendering (SVG based)
function renderDashboardCharts() {
    const labels = [];
    let visitsData = [];
    let revenueData = [];

    const labelsContainer = document.getElementById("chart-labels");
    labelsContainer.innerHTML = "";

    if (chartViewMode === 'daily') {
        const hours = currentLang === 'ar' ? ['٦ص', '٩ص', '١٢م', '٣م', '٦م', '٩م'] : ['6am', '9am', '12pm', '3pm', '6pm', '9pm'];
        visitsData = [5, 9, 12, 18, 15, 11];
        revenueData = [120, 220, 310, 430, 390, 320];
        hours.forEach(hour => {
            labels.push(hour);
            const labelSpan = document.createElement('span');
            labelSpan.textContent = hour;
            labelsContainer.appendChild(labelSpan);
        });
    } else if (chartViewMode === 'monthly') {
        const baseVisits = [45, 60, 55, 70, 65, 80];
        const baseRevenue = [4000, 5500, 4800, 6200, 5800, 7100];
        visitsData = [0, 0, 0, 0, 0, 0];
        revenueData = [0, 0, 0, 0, 0, 0];
        
        const now = new Date();
        const monthsIntervals = [];
        for (let i = 5; i >= 0; i--) {
            const start = new Date(now.getFullYear(), now.getMonth() - i, 1);
            const end = new Date(now.getFullYear(), now.getMonth() - i + 1, 0, 23, 59, 59);
            monthsIntervals.push({ start, end });
            
            const monthName = translations[currentLang].months[start.getMonth()];
            labels.push(monthName);
            const labelSpan = document.createElement('span');
            labelSpan.textContent = monthName;
            labelsContainer.appendChild(labelSpan);
        }
        
        monthsIntervals.forEach((interval, index) => {
            const countApp = db.appointments.filter(app => {
                const appDate = new Date(app.date);
                return appDate >= interval.start && appDate <= interval.end && app.status === 'completed';
            }).length;
            visitsData[index] = countApp + baseVisits[index];

            const sumRev = db.invoices.filter(inv => {
                const invDate = new Date(inv.date);
                return invDate >= interval.start && invDate <= interval.end && inv.status === 'paid';
            }).reduce((sum, inv) => sum + inv.total, 0);
            revenueData[index] = sumRev + baseRevenue[index];
        });
    } else {
        const weeklyData = {
            visits: [12, 19, 15, 25, 22, 30, 42],
            revenue: [800, 1200, 950, 1800, 1500, 2100, 4850]
        };
        visitsData = weeklyData.visits;
        revenueData = weeklyData.revenue;

        for (let i = 6; i >= 0; i--) {
            const d = new Date();
            d.setDate(d.getDate() - i);
            const dayName = translations[currentLang].weekdays[d.getDay()];
            labels.push(dayName);
            const labelSpan = document.createElement('span');
            labelSpan.textContent = dayName;
            labelsContainer.appendChild(labelSpan);
        }
    }

    const pointsCount = visitsData.length;
    const chartSize = pointsCount - 1;
    const startX = 40;
    const endX = 580;
    const startY = 170;
    const endY = 20;
    const stepX = chartSize > 0 ? (endX - startX) / chartSize : 0;

    const maxVisits = Math.max(...visitsData, 10);
    const maxRevenue = Math.max(...revenueData, 200);

    const visitsPoints = [];
    const revenuePoints = [];

    for (let i = 0; i < pointsCount; i++) {
        const x = startX + (i * stepX);
        const yVisits = startY - ((visitsData[i] / maxVisits) * (startY - endY));
        const yRevenue = startY - ((revenueData[i] / maxRevenue) * (startY - endY));
        visitsPoints.push(`${x},${yVisits}`);
        revenuePoints.push(`${x},${yRevenue}`);
    }

    const chartPaths = document.getElementById("chart-paths");
    chartPaths.innerHTML = `
        <polyline fill="none" stroke="var(--accent-secondary)" stroke-width="3" stroke-linecap="round" stroke-linejoin="round" points="${visitsPoints.join(" ")}" />
        ${visitsPoints.map(p => `<circle cx="${p.split(",")[0]}" cy="${p.split(",")[1]}" r="5" fill="var(--bg-secondary)" stroke="var(--accent-secondary)" stroke-width="2" />`).join("")}
        <polyline fill="none" stroke="var(--color-amber)" stroke-width="3" stroke-linecap="round" stroke-linejoin="round" points="${revenuePoints.join(" ")}" />
        ${revenuePoints.map(p => `<circle cx="${p.split(",")[0]}" cy="${p.split(",")[1]}" r="5" fill="var(--bg-secondary)" stroke="var(--color-amber)" stroke-width="2" />`).join("")}
    `;
}

