// Standalone keyboard shortcuts for staff and admin
document.addEventListener("keydown", (e) => {
    if (!e.altKey) return;
    const activeEl = document.activeElement;
    if (activeEl && (activeEl.tagName === 'INPUT' || activeEl.tagName === 'TEXTAREA' || activeEl.isContentEditable)) {
        return;
    }

    const key = e.key.toLowerCase();
    
    // Alt + H -> Home (Dashboard)
    if (key === 'h') {
        e.preventDefault();
        switchPanel("dashboard");
    }
    // Alt + P -> Patients
    else if (key === 'p') {
        e.preventDefault();
        switchPanel("patients");
    }
    // Alt + A -> Appointments
    else if (key === 'a') {
        e.preventDefault();
        switchPanel("appointments");
    }
    // Alt + D -> Doctors
    else if (key === 'd') {
        e.preventDefault();
        switchPanel("doctors");
    }
    // Alt + B -> Billing
    else if (key === 'b') {
        e.preventDefault();
        switchPanel("billing");
    }
    // Alt + I -> Inventory / Reports
    else if (key === 'i') {
        e.preventDefault();
        switchPanel("inventory");
    }
    // Alt + S -> Settings
    else if (key === 's') {
        e.preventDefault();
        switchPanel("settings");
    }
    // Alt + L -> Logout
    else if (key === 'l') {
        e.preventDefault();
        handleLogout();
    }
});

