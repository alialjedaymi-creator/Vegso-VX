async function autoClassifyAppointments() {
    if (!db || !db.appointments) return;
    const todayStr = new Date().toISOString().split("T")[0];
    let changed = false;
    for (let app of db.appointments) {
        let targetStatus = app.status;
        if (app.date < todayStr) {
            if (app.status === 'pending' || app.status === 'confirmed') {
                targetStatus = 'completed';
            }
        } else if (app.date === todayStr) {
            if (app.status === 'confirmed') {
                targetStatus = 'pending';
            }
        } else {
            if (app.status === 'pending') {
                targetStatus = 'confirmed';
            }
        }
        
        if (targetStatus !== app.status) {
            try {
                await apiCall('PATCH', `/appointments/${app.id}/status`, { status: targetStatus });
                app.status = targetStatus;
                if (targetStatus === 'completed') {
                    const doctor = db.doctors.find(d => d.id === app.doctorId);
                    if (doctor) doctor.visits += 1;
                }
                changed = true;
            } catch (e) {
                console.error("Auto-classify failed for app", app.id, e);
            }
        }
    }
    return changed;
}

