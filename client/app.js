        const item = document.createElement('div');
        item.className = 'noti-item';
        const color = iss.level === 'error' ? '#f43f5e' : '#eab308';
        const bg = iss.level === 'error' ? 'rgba(244, 63, 94, 0.15)' : 'rgba(234, 179, 8, 0.15)';
